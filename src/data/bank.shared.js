/*!
 * bank.shared.js —— 共享题库（随网站一起发布，所有使用者都能看到）
 *
 * ＝＝＝＝＝＝＝＝＝＝＝＝＝＝＝＝＝＝＝＝＝＝＝＝＝＝＝＝＝＝＝＝＝＝＝＝＝＝
 *  这个文件是"共享题库"的容器。它和「个人题库」的区别：
 *
 *    · 共享题库（本文件）：跟着网站一起发布出去。
 *      你更新它 → 重新发布 → 所有使用者刷新页面就能拿到新题。
 *    · 个人题库（浏览器本地）：使用者在「题库导入」页自己传的题，
 *      只存在他自己的浏览器里，别人看不到。
 *
 *  合并优先级：内置题库 > 共享题库 > 个人题库
 *  （同 id 时保留优先级高的那一份，所以你能用本文件更新使用者手里的旧题）
 *
 *  怎么往里加题（两种方式，任选其一）：
 *
 *  方式一（推荐，不用手写代码）：
 *    1. 打开网站 →「题库导入」页 → 下载 CSV 模板 → 填好题 → 上传 → 解析并预览
 *    2. 点「导出为共享题库文件」，会下载一个 bank.shared.js
 *    3. 用它覆盖本项目 src/data/bank.shared.js
 *    4. 双击「发布.cmd」 → 把 dist 里的内容重新上传
 *    5. 使用者刷新页面 → 顶部提示有新版本 → 点刷新，新题库就到手了
 *
 *  方式二（在项目根目录放 JSON，让发布脚本自动转换）：
 *    1. 把题库整理成 JSON（格式见 SCHEMA.md 第 9 节），存成
 *       项目根目录下的「共享题库.json」
 *    2. 双击「发布.cmd」——发布脚本会自动读它并生成本文件的内容
 *
 *  格式与内置题库完全一致，见 SCHEMA.md §3。
 * ＝＝＝＝＝＝＝＝＝＝＝＝＝＝＝＝＝＝＝＝＝＝＝＝＝＝＝＝＝＝＝＝＝＝＝＝＝＝
 */
(function (global) {
  'use strict';
  var KY = (global.KY = global.KY || {});

  /**
   * 共享题库题目数组。
   * 元素结构同 SCHEMA.md §3 的 question，必须有 id / subject / knowledge / answer。
   */
  KY.sharedBank = KY.sharedBank || [];

  /** 共享题库的版本标记，由 tools/release.js 在发布时写入，便于排查问题 */
  KY.sharedBankMeta = KY.sharedBankMeta || {
    builtAt: '',
    count: 0,
    source: 'empty'
  };
})(window);
