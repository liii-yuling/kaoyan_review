/*!
 * push.shared.js —— 共享错题推送（运营者挑题，使用者一键收进错题本）
 *
 * ＝＝＝＝＝＝＝＝＝＝＝＝＝＝＝＝＝＝＝＝＝＝＝＝＝＝＝＝＝＝＝＝＝＝＝＝＝＝
 *  用途：你（运营者）从题库里挑几道题，指定给她练，并写一句提醒。
 *        她打开网站会看到「布置给我的错题」，点一下就全部进她自己的错题本，
 *        然后照常参与错题复习与推题。
 *
 *  为什么不能直接改她的错题本：她的错题本存在她自己浏览器里，
 *  你这边碰不到（这也是"不租服务器"的必然结果）。
 *  所以做法是"你推送清单 → 她一键收下"，收下之后数据就归她自己管。
 *
 *  怎么填：
 *    1. 打开「运营台」页 → 「错题推送」编辑框
 *    2. 每行写「题目 ID 或题干关键词 | 你想说的话」
 *    3. 点「导出推送文件」→ 得到 push.shared.js
 *    4. 覆盖本文件 → 双击「发布.cmd」→ 上传 dist
 *    5. 她刷新页面就能看到并一键收下
 *
 *  文本格式示例：
 *
 *    en1-2023-cloze-01 | 这道题的逻辑衔接你上次错了，注意 however 的用法
 *    数学一 洛必达 | 你昨天错在这里，今天重做一遍
 *    m1-2020-limit-01
 *
 *  说明：
 *    · 没写 | 备注 也可以，只有题目。
 *    · 关键词写法只在能唯一匹配到一道题时生效；匹配到多道会提示你改用题目 ID。
 *    · 她收下后，这道题会带上你的备注进她的错题本，并自动归类考点与错因。
 *
 *  格式规范见 SCHEMA.md 第 12 节。
 * ＝＝＝＝＝＝＝＝＝＝＝＝＝＝＝＝＝＝＝＝＝＝＝＝＝＝＝＝＝＝＝＝＝＝＝＝＝＝
 */
(function (global) {
  'use strict';
  var KY = (global.KY = global.KY || {});

  /** 推送清单；由「运营台」导出后覆盖本文件 */
  KY.sharedWrongPush = KY.sharedWrongPush || {
    updatedAt: '',
    title: '',
    items: []          // [{ questionId, note, addedAt }]
  };

  /** 发布元信息 */
  KY.sharedWrongPushMeta = KY.sharedWrongPushMeta || {
    builtAt: '',
    count: 0,
    source: 'empty'
  };
})(window);
